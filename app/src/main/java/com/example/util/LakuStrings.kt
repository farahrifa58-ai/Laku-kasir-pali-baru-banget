    fun localeFor(lang: String = "id"): Locale {
        return when (lang.lowercase().trim()) {
            "id" -> Locale("id", "ID")
            "ms" -> Locale("ms", "MY")
            "vi" -> Locale("vi", "VN")
            "th" -> Locale("th", "TH")
            "fil" -> Locale("tl", "PH")
            "ja" -> Locale.JAPAN
            "ko" -> Locale.KOREA
            "zh" -> Locale.SIMPLIFIED_CHINESE
            "hi" -> Locale("hi", "IN")
            "ar" -> Locale("ar", "SA")
            "ru" -> Locale("ru", "RU")
            "de" -> Locale.GERMANY
            "fr" -> Locale.FRANCE
            "es" -> Locale("es", "ES")
            "it" -> Locale.ITALY
            "nl" -> Locale("nl", "NL")
            "pt" -> Locale("pt", "BR")
            "sw" -> Locale("sw", "KE")
            else -> Locale.ENGLISH
        }
    }

    fun get(key: String, lang: String = "id"): String {
        val l = lang.lowercase().trim()
        if (l == "id") return getIndonesian(key)
        if (l == "en") return getEnglish(key)
        return LakuStringsRegional.getRegional(key, l) ?: getEnglish(key)
    }

    fun translateCategory(raw: String, lang: String): String {
        val key = when (raw.trim().lowercase()) {
            "semua" -> "all"
            "makanan & minuman" -> "cat_food_drink"
            "sayur & buah" -> "cat_veg_fruit"
            "sembako" -> "cat_groceries"
            "fashion" -> "cat_fashion"
            "elektronik" -> "cat_electronics"
            "bangunan" -> "cat_hardware"
            "lainnya" -> "cat_other"
            else -> return raw
        }
        return get(key, lang)
    }

